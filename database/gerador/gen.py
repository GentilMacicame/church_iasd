def sub(t, s):
    return re.sub(r'@(\w+)', lambda m: f'{t.p}_{m.group(1)}', s).replace('{t}', q(t))

def pktype(t): return 'BIGINT' if t.big else 'INT'

def table_sql(t, created, pending):
    if t.partition:
        lines = [f'    {t.p}_id BIGSERIAL']
    else:
        lines = [f'    {t.p}_id {pktype(t)} GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY']
    fks = []
    for c in t.cols:
        name, typ = c[0], c[1]
        opt = c[2] if len(c) > 2 else ''
        col = f'{t.p}_{name}'
        if typ.startswith('fk:'):
            ref = BY[typ[3:]]
            fks.append((col, ref))
            typ = pktype(ref)
        lines.append(f'    {col} {typ}{" " + opt if opt else ""}')
    et, ed = t.estado
    lines += [f'    {t.p}_estado {et} NOT NULL DEFAULT {ed}',
              f'    {t.p}_criado_em TIMESTAMPTZ NOT NULL DEFAULT now()',
              f'    {t.p}_criado_por INT',
              f'    {t.p}_modificado_em TIMESTAMPTZ NOT NULL DEFAULT now()',
              f'    {t.p}_modificado_por INT',
              f'    {t.p}_end_date TIMESTAMPTZ']
    cons = []
    if t.partition:
        cons.append(f'    PRIMARY KEY ({t.p}_id, {sub(t, t.partition)})')
    for col, ref in fks:
        cname = f'fk_{col}'[:63]
        stmt = f'FOREIGN KEY ({col}) REFERENCES {q(ref)}({ref.p}_id)'
        if ref.name in created or ref.name == t.name:
            cons.append(f'    CONSTRAINT {cname} {stmt}')
        else:
            pending.setdefault(ref.name, []).append(f'ALTER TABLE {q(t)} ADD CONSTRAINT {cname} {stmt};')
    for ck in t.checks:
        cons.append(f'    CONSTRAINT {ck[0]} CHECK ({sub(t, ck[1])})')
    cons.append(f'    CONSTRAINT chk_{t.p}_end_date CHECK ({t.p}_end_date IS NULL OR {t.p}_end_date >= {t.p}_criado_em)')
    tail = f' PARTITION BY RANGE ({sub(t, t.partition)})' if t.partition else ''
    out = [f'-- {t.desc}', f'CREATE TABLE {q(t)} (', ',\n'.join(lines + cons), f'){tail};']
    out.append(f"COMMENT ON TABLE {q(t)} IS '{t.desc.replace(chr(39), chr(39)*2)}';")
    for c in t.cols:
        if len(c) > 3 and c[3]:
            out.append(f"COMMENT ON COLUMN {q(t)}.{t.p}_{c[0]} IS '{c[3].replace(chr(39), chr(39)*2)}';")
    for u in t.uniq:
        cols = ', '.join(f'{t.p}_{x}' for x in u)
        iname = (f'uq_{t.p}_' + '_'.join(u))[:63]
        out.append(f'CREATE UNIQUE INDEX {iname} ON {q(t)} ({cols}) WHERE {t.p}_end_date IS NULL;')
    covered = {f'{t.p}_{u[0]}' for u in t.uniq}
    for col, ref in fks:
        if col in covered: continue
        out.append(f'CREATE INDEX {("idx_" + col)[:63]} ON {q(t)} ({col});')
    for x in t.extra:
        out.append(sub(t, x) + ';')
    if t.partition:
        out.append(f'CREATE TABLE {q(t)}_default PARTITION OF {q(t)} DEFAULT;')
        out.append(f'SELECT nucleo.fn_criar_particoes_log(12);')
    return '\n'.join(out)

def read(name):
    p = os.path.join(SQL, name)
    return open(p).read() if os.path.exists(p) else ''

