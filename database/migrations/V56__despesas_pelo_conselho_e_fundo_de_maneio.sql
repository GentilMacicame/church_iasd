    INSERT INTO nucleo.fluxo_etapa (fae_fap_id, fae_ordem, fae_nome, fae_accao, fae_responsavel, fae_orgao) VALUES
        (f, 1, 'Voto do Conselho da Igreja', 'VOTAR', 'ORGAO', 'JUNTA_DIRECTIVA');
