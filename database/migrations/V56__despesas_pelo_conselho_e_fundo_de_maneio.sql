                                                WHERE fap_igr_id IS NULL AND fap_processo IN ('DESPESA', 'SAIDA') AND fap_end_date IS NULL);
UPDATE nucleo.fluxo_aprovacao SET fap_end_date = now()
 WHERE fap_igr_id IS NULL AND fap_processo IN ('DESPESA', 'SAIDA') AND fap_end_date IS NULL;

