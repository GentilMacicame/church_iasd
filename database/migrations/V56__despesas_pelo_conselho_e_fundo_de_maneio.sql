DECLARE f INT; p TEXT;
    p_tes INT := (SELECT per_id FROM nucleo.perfil WHERE per_codigo = 'TESOUREIRO');
    m_tra INT := (SELECT prm_id FROM nucleo.permissao WHERE prm_codigo = 'tesouraria.transacao.aprovar');
