CREATE INDEX idx_aco_igr_pagina ON nucleo.acesso_confidencial (aco_igr_id, aco_id);
CREATE INDEX idx_aco_igr_data ON nucleo.acesso_confidencial (aco_igr_id, aco_criado_em DESC);

