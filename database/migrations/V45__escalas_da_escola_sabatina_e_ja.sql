--   lembretes         nas colunas da ES/JA o SMS diz o nome da coluna (ex.: "apresentador da Escola Sabatina").
--
-- Nada se apaga: o tipo dos planos existentes é CULTO; eds_fam_id (V44) fica, sem uso na grelha.
