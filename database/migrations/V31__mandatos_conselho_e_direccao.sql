    mdt_observacoes VARCHAR(255),
    mdt_estado estado_registo_t NOT NULL DEFAULT 'ACTIVO',
    mdt_criado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
    mdt_criado_por INT,
    mdt_modificado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
