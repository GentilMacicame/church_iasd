/** Substitui {chave} no texto: f(t.membros.terminarTitulo, { nome: 'Ana' }). */
export function f(texto: string, valores: Record<string, string | number>): string {
  return texto.replace(/\{(\w+)\}/g, (_, k: string) => String(valores[k] ?? ''))
}

